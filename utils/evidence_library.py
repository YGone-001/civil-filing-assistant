class EvidenceLibrary:
    @staticmethod
    def get_default_evidence(case_type):
        if case_type == "loan":
            return [
                ("借条/借款协议", "证明双方存在借贷合意、借款金额及还款约定。"),
                ("银行转账凭证/现金收据", "证明原告已实际出借款项。"),
                ("催款聊天记录/通话录音/催告函", "证明原告已催告，被告仍未履行。"),
            ]
        if case_type == "contract":
            return [
                ("买卖合同/采购单/订单", "证明合同关系成立及主要权利义务内容。"),
                ("送货单/物流签收单/入库单", "证明原告履行交付义务及被告签收情况。"),
                ("发票/对账单/对账确认单/催款函", "证明价款结算依据、欠款金额及催告事实。"),
            ]
        if case_type == "property":
            return [
                ("物业服务合同/服务标准公示材料", "证明物业服务关系及收费标准依据。"),
                ("欠费明细表/计费依据材料", "证明欠费期间、计费标准及计算过程。"),
                ("催缴通知书及送达证据", "证明已履行催告义务及送达事实。"),
            ]
        if case_type == "labor":
            return [
                ("劳动合同/入职通知书", "证明劳动关系的存在。"),
                ("工资条/银行流水/个税记录", "证明工资标准及欠薪数额。"),
                ("考勤记录/加班审批单", "证明工作时长及加班事实。"),
                ("解除劳动关系通知书/离职证明", "明确劳动关系终止时间。"),
            ]
        if case_type == "divorce":
            return [
                ("结婚证/户口本", "证明双方存在法律上的夫妻关系。"),
                ("出生医学证明", "证明父母子女关系及子女年龄。"),
                ("财产凭证（产证/存折）", "证明婚后共有财产的范围与价值。"),
                ("收入证明/银行流水", "证明双方经济能力，作为抚养费判定依据。"),
            ]
        return [
            ("合同/协议/事实依据材料", "证明双方权利义务基础关系。"),
            ("履行凭证/对账材料", "证明履行情况、欠款（或损失）金额。"),
            ("催告材料", "证明催告事实及对方仍未履行。"),
        ]
